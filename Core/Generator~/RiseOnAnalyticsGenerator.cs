using System.IO;
using System.Linq;
using System.Security;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace RiseOn.Analytics.Generator {
    /// <summary>
    /// Compiles into RiseOn.Analytics the events the settings page lists: the enum AnalyticsEvent, numbered by each event's id, and the name each member sends.<br/>
    /// Members are named by the event as written, with @ before a C# keyword.<br/>
    /// Nothing is written to disk, so nobody can edit it.
    /// </summary>
    [Generator]
    public sealed class RiseOnAnalyticsGenerator : ISourceGenerator {
        private const string PackAssembly = "RiseOn.Analytics";
        private const string EventsFile   = ".RiseOnAnalyticsGenerator.additionalfile";

        private static readonly DiagnosticDescriptor badLine = new(
            "RISEONAN001", "Unreadable event line", "{0} line {1} is not 'id, name, description' split by tabs; open Project Settings > RiseOn > Analytics to write it again",
            "RiseOn.Analytics", DiagnosticSeverity.Error, true);

        public void Initialize(GeneratorInitializationContext context) { }

        public void Execute(GeneratorExecutionContext context) {
            if (context.Compilation.AssemblyName is not PackAssembly) return;

            var members = new StringBuilder();
            var names   = new StringBuilder();
            foreach (var file in context.AdditionalFiles.Where(file => file.Path.EndsWith(EventsFile))) {
                var lines = file.GetText(context.CancellationToken)?.Lines;
                if (lines == null) continue;

                for (var i = 0; i < lines.Count; ++i) {
                    var line = lines[i].ToString();
                    if (line.Trim().Length == 0) continue;

                    var parts = line.Split('\t');
                    if (parts.Length != 3 || !int.TryParse(parts[0], out var id) || id <= 0 || !SyntaxFacts.IsValidIdentifier(parts[1])) {
                        context.ReportDiagnostic(Diagnostic.Create(badLine, Location.None, Path.GetFileName(file.Path), i + 1));
                        continue;
                    }

                    if (parts[2].Length > 0) members.Append($"        /// <summary>{SecurityElement.Escape(parts[2])}</summary>\n");
                    var member = SyntaxFacts.GetKeywordKind(parts[1]) is SyntaxKind.None ? parts[1] : "@" + parts[1];
                    members.Append($"        {member} = {id},\n");
                    names.Append($"                case {id}: return \"{parts[1]}\";\n");
                }
            }

            var code = new StringBuilder();
            code.Append("// <auto-generated/>\n");
            code.Append("namespace RiseOn.Analytics {\n");
            code.Append("    /// <summary>The events of Project Settings > RiseOn > Analytics.</summary>\n");
            code.Append("    public enum AnalyticsEvent {\n");
            code.Append(members);
            code.Append("    }\n\n");
            code.Append("    internal static class AnalyticsEventNames {\n");
            code.Append("        /// <summary>The name the services get; null for a number that is no event.</summary>\n");
            code.Append("        public static string Of(AnalyticsEvent value) {\n");
            code.Append("            switch ((int)value) {\n");
            code.Append(names);
            code.Append("                default: return null;\n");
            code.Append("            }\n");
            code.Append("        }\n");
            code.Append("    }\n}\n");
            context.AddSource("AnalyticsEvent.g.cs", SourceText.From(code.ToString(), Encoding.UTF8));
        }
    }
}